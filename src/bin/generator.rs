struct GenApp {
    size: usize,
    givens: usize,
    seed: u64,
    max_passes: usize,
    force_query: bool,
    query_r: usize,
    query_c: usize,
    show_solution: bool,
    show_colors: bool,
    out_path: String,
    current: Option<Generated>,
    status: String,
}

impl GenApp {
    fn new(_cc: &eframe::CreationContext<'_>) -> Self {
        let seed = random_seed();
        let mut app = Self {
            size: 5,
            givens: 11,
            seed,
            max_passes: 3,
            force_query: false,
            query_r: 0,
            query_c: 1,
            show_solution: true,
            show_colors: true,
            out_path: String::new(),
            current: None,
            status: "Press Generate.".to_string(),
        };
        app.generate();
        app
    }

    fn opts(&self) -> GenOptions {
        GenOptions {
            size: self.size,
            givens: self.givens.min(self.size * self.size - 1),
            seed: self.seed,
            max_passes: self.max_passes.max(1),
            query: self.force_query.then_some((self.query_r, self.query_c)),
        }
    }

    fn generate(&mut self) {
        match generate(&self.opts()) {
            Ok(g) => {
                self.status = format!("generated. {}", g.summary());
                self.current = Some(g);
                if self.out_path.is_empty() {
                    if let Some(cur) = &self.current {
                        self.out_path = format!(
                            "puzzles/generated_s{}g{}_seed{}.txt",
                            cur.size, cur.givens, cur.seed
                        );
                    }
                }
            }
            Err(e) => {
                self.status = format!("generation failed: {}", e);
                self.current = None;
            }
        }
    }

    fn save_current(&mut self) {
        let Some(g) = &self.current else {
            self.status = "nothing to save yet".to_string();
            return;
        };
        if self.out_path.trim().is_empty() {
            self.status = "output path is empty".to_string();
            return;
        }
        let path = std::path::Path::new(self.out_path.trim());
        if let Some(parent) = path.parent() {
            if !parent.as_os_str().is_empty() {
                if let Err(e) = std::fs::create_dir_all(parent) {
                    self.status = format!("cannot create {}: {}", parent.display(), e);
                    return;
                }
            }
        }
        match std::fs::write(path, render_file_text(g, true)) {
            Ok(()) => self.status = format!("saved to {}", path.display()),
            Err(e) => self.status = format!("cannot write {}: {}", path.display(), e),
        }
    }
}

impl eframe::App for GenApp {
    fn ui(&mut self, ui: &mut egui::Ui, _frame: &mut eframe::Frame) {
        ui.horizontal(|ui| {
            ui.heading("Et Tu — problem generator");
            ui.label("(random Latin-square puzzles with unique solutions)");
        });
        ui.separator();

        ui.horizontal(|ui| {
            // ---- left: puzzle preview ----
            ui.vertical(|ui| {
                ui.label("Preview (thick border = given, orange = ?)");
                if let Some(g) = &self.current {
                    let n = g.size;
                    let cell = (64.0_f32).min(360.0 / n as f32).max(30.0);
                    let sol = &g.solution;
                    for r in 0..n {
                        ui.horizontal(|ui| {
                            ui.spacing_mut().item_spacing = egui::Vec2::splat(4.0);
                            for c in 0..n {
                                let flat = r * n + c;
                                let given = g.puzzle.cells[flat];
                                let is_query = g.puzzle.query == Some((r, c));
                                let shown = match given {
                                    Some(v) => Some(v),
                                    None if self.show_solution => Some(sol[flat]),
                                    None => None,
                                };
                                let deduced = given.is_none() && shown.is_some();
                                let (rect, _) = ui.allocate_exact_size(
                                    egui::Vec2::splat(cell),
                                    egui::Sense::hover(),
                                );
                                let painter = ui.painter();
                                let bg = if is_query {
                                    egui::Color32::from_rgb(255, 252, 220)
                                } else if given.is_some() {
                                    egui::Color32::from_rgb(238, 238, 240)
                                } else {
                                    egui::Color32::WHITE
                                };
                                painter.rect_filled(rect, 0.0, bg);
                                let border = if is_query {
                                    egui::Stroke::new(2.5, egui::Color32::from_rgb(230, 140, 0))
                                } else if given.is_some() {
                                    egui::Stroke::new(2.0, egui::Color32::BLACK)
                                } else {
                                    egui::Stroke::new(1.0, egui::Color32::from_rgb(200, 200, 205))
                                };
                                painter.rect_stroke(rect, 0.0, border, egui::StrokeKind::Inside);
                                match shown {
                                    Some(v) => {
                                        paint_symbol(
                                            painter,
                                            rect.shrink(5.0),
                                            v,
                                            self.show_colors,
                                            n,
                                        );
                                        if deduced {
                                            let d = rect.left_top() + egui::Vec2::splat(3.0);
                                            painter.circle_filled(
                                                d,
                                                2.0,
                                                egui::Color32::from_rgb(150, 150, 155),
                                            );
                                        }
                                    }
                                    None if is_query => {
                                        painter.text(
                                            rect.center(),
                                            egui::Align2::CENTER_CENTER,
                                            "?",
                                            egui::FontId::proportional(cell * 0.55),
                                            egui::Color32::from_rgb(90, 90, 90),
                                        );
                                    }
                                    None => {}
                                }
                            }
                        });
                    }
                    if let Some((qr, qc)) = g.puzzle.query {
                        let v = sol[qr * n + qc];
                        ui.label(format!(
                            "? at ({},{}) = {} ({})",
                            qr,
                            qc,
                            symbol_name(v),
                            color_word(v)
                        ));
                    }
                    ui.label(format!(
                        "givens={} checks={} elapsed={}ms",
                        g.givens, g.uniqueness_checks, g.elapsed_ms
                    ));
                    ui.label(format!(
                        "difficulty: attempts={} backtracks={}{}",
                        g.difficulty_attempts,
                        g.difficulty_backtracks,
                        if g.difficulty_capped {
                            " (probe capped: hard)"
                        } else {
                            ""
                        }
                    ));
                } else {
                    ui.label("no puzzle yet");
                }
                ui.label(format!("status: {}", self.status));
            });

            ui.separator();

            // ---- right: controls ----
            ui.vertical(|ui| {
                ui.heading("Settings");
                ui.horizontal(|ui| {
                    ui.label("Size:");
                    ui.add(egui::DragValue::new(&mut self.size).range(2..=9));
                    if ui.button("5×5").clicked() {
                        self.size = 5;
                    }
                });
                ui.horizontal(|ui| {
                    ui.label("Givens target:");
                    let max = self.size * self.size - 1;
                    ui.add(egui::DragValue::new(&mut self.givens).range(0..=max));
                    if self.givens > max {
                        self.givens = max;
                    }
                    if ui.button("11").clicked() {
                        self.givens = 11.min(max);
                    }
                });
                ui.horizontal(|ui| {
                    ui.label("Seed:");
                    ui.add(egui::DragValue::new(&mut self.seed));
                    if ui.button("🎲").on_hover_text("random seed").clicked() {
                        self.seed = random_seed();
                    }
                });
                ui.horizontal(|ui| {
                    ui.label("Dig passes:");
                    ui.add(egui::DragValue::new(&mut self.max_passes).range(1..=10));
                });
                ui.horizontal(|ui| {
                    ui.checkbox(&mut self.force_query, "pin ? at");
                    ui.add(egui::DragValue::new(&mut self.query_r).range(0..=self.size - 1));
                    ui.label(",");
                    ui.add(egui::DragValue::new(&mut self.query_c).range(0..=self.size - 1));
                });
                ui.horizontal(|ui| {
                    if ui.button("⚙ Generate").clicked() {
                        self.generate();
                    }
                    if ui
                        .button("🎲 Randomize & generate")
                        .on_hover_text("new random seed, then generate")
                        .clicked()
                    {
                        self.seed = random_seed();
                        self.generate();
                    }
                    if ui.button("Example-like").clicked() {
                        self.size = 5;
                        self.givens = 11;
                        self.force_query = false;
                        self.generate();
                    }
                });
                ui.checkbox(&mut self.show_solution, "Show solution in holes (dotted)");
                ui.checkbox(&mut self.show_colors, "Show colours");
                ui.separator();
                ui.label("Save (solver-loadable text + answer key in # comments):");
                ui.horizontal(|ui| {
                    ui.label("Path:");
                    ui.add(egui::TextEdit::singleline(&mut self.out_path).desired_width(220.0));
                });
                ui.horizontal(|ui| {
                    if ui.button("💾 Save").clicked() {
                        self.save_current();
                    }
                    if ui.button("📋 Copy text").clicked() {
                        if let Some(g) = &self.current {
                            ui.ctx().copy_text(render_file_text(g, true));
                            self.status = "copied to clipboard".to_string();
                        }
                    }
                });
                if let Some(g) = &self.current {
                    ui.separator();
                    ui.label("Puzzle text:");
                    let mut txt = render_file_text(g, true);
                    ui.add(
                        egui::TextEdit::multiline(&mut txt)
                            .desired_rows(10)
                            .desired_width(300.0)
                            .font(egui::TextStyle::Monospace),
                    );
                }
                ui.separator();
                ui.label("Tip: load a saved file in the solver (et_tu) via its puzzle-text box,");
                ui.label("or: et_tu --headless --puzzle <file>");
                let _ = Puzzle::example_png;
            });
        });
    }
}

// ---------------------------------------------------------------------------
// Entry
// ---------------------------------------------------------------------------

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let want_gui = args.is_empty() || args.iter().any(|a| a == "--gui");
    if !want_gui {
        std::process::exit(run_headless(&args));
    }
    let native_options = eframe::NativeOptions {
        viewport: egui::ViewportBuilder::default().with_inner_size([1020.0, 700.0]),
        ..Default::default()
    };
    if let Err(e) = eframe::run_native(
        "Et Tu — problem generator",
        native_options,
        Box::new(|cc: &eframe::CreationContext| {
            Ok(Box::new(GenApp::new(cc)) as Box<dyn eframe::App>)
        }),
    ) {
        eprintln!("GUI failed to start: {:?}.", e);
        print_usage();
        std::process::exit(1);
    }
}
