//! Et Tu — companion problem generator.
//!
//! Generates random uniquely-solvable Latin-square shape puzzles like
//! `et tu problem.png` (each symbol once per row and column).
//!
//! Usage:
//! * GUI (no arguments): `cargo run --bin et_tu_generator`
//! * Headless: `et_tu_generator --size 5 --givens 11 --seed 99 --count 3
//!   --out puzzles/ [--no-solution] [--query 0,1]`

use eframe::egui;
use et_tu::gen::{generate, GenOptions, Generated, Rng};
use et_tu::{symbol_name, Puzzle};

#[path = "../paint.rs"]
mod paint;
use paint::{color_word, paint_symbol};

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

fn random_seed() -> u64 {
    use std::time::{SystemTime, UNIX_EPOCH};
    let raw = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs().wrapping_mul(0x9E37_79B9_7F4A_7C15) ^ d.subsec_nanos() as u64)
        .unwrap_or(0x1234_5678_9ABC_DEF0);
    // Mix once so closely-spaced calls still differ wildly.
    let mut rng = Rng::new(raw.wrapping_add(0x9E37_79B9_7F4A_7C15));
    rng.next_u64()
}

fn parse_query(s: &str) -> Result<(usize, usize), String> {
    let parts: Vec<&str> = s.split([',', ' ', ':']).filter(|p| !p.is_empty()).collect();
    if parts.len() != 2 {
        return Err(format!("--query expects r,c (got {:?})", s));
    }
    let r: usize = parts[0]
        .parse()
        .map_err(|_| format!("bad query row in {:?}", s))?;
    let c: usize = parts[1]
        .parse()
        .map_err(|_| format!("bad query column in {:?}", s))?;
    Ok((r, c))
}

/// File/comment-safe rendering: `#` header lines (ignored by the solver's
/// text parser) plus the loadable puzzle body.
fn render_file_text(g: &Generated, with_solution: bool) -> String {
    let mut out = String::new();
    let (qr, qc) = g.puzzle.query.unwrap_or((0, 0));
    let qv = g.solution[qr * g.size + qc];
    out.push_str(&format!(
        "# generated by et_tu_generator ({})\n",
        g.summary()
    ));
    out.push_str(&format!(
        "# query ({},{}) = {} ({})\n",
        qr,
        qc,
        symbol_name(qv),
        color_word(qv)
    ));
    out.push_str(&g.puzzle.to_text());
    if with_solution {
        out.push_str("# solution:\n");
        for r in 0..g.size {
            out.push_str("# ");
            for c in 0..g.size {
                if c > 0 {
                    out.push(' ');
                }
                let v = g.solution[r * g.size + c];
                if g.size == 5 {
                    out.push(et_tu::symbol_glyph(v));
                } else {
                    out.push_str(&(v + 1).to_string());
                }
            }
            out.push('\n');
        }
    }
    out
}

fn print_usage() {
    eprintln!("Et Tu — companion problem generator");
    eprintln!("GUI:      et_tu_generator            (no arguments)");
    eprintln!("Headless: et_tu_generator [options]");
    eprintln!("  --size N        grid size 2..=9 (default 5)");
    eprintln!("  --givens G      target givens (default 11; clamped to N*N-1)");
    eprintln!("  --seed S        base seed (default: time-based, printed in output)");
    eprintln!("  --count K       generate K puzzles with seeds S..S+K-1 (default 1)");
    eprintln!("  --out PATH      file (count=1) or directory (count>1); else stdout");
    eprintln!("  --query r,c     pin the ? cell (default: random hole)");
    eprintln!("  --max-passes P  hole-digging passes (default 3)");
    eprintln!("  --no-solution   omit the answer key from the output");
    eprintln!("  --gui           force the GUI even with other arguments");
}

// ---------------------------------------------------------------------------
// Headless mode
// ---------------------------------------------------------------------------

fn run_headless(args: &[String]) -> i32 {
    let mut size = 5usize;
    let mut givens = 11usize;
    let mut seed_opt: Option<u64> = None;
    let mut count = 1usize;
    let mut out: Option<String> = None;
    let mut query: Option<(usize, usize)> = None;
    let mut max_passes = 3usize;
    let mut with_solution = true;

    let mut i = 0;
    while i < args.len() {
        match args[i].as_str() {
            "--size" => {
                i += 1;
                size = match args.get(i).and_then(|s| s.parse().ok()) {
                    Some(v) => v,
                    None => {
                        eprintln!("--size needs a number 2..=9");
                        return 2;
                    }
                };
            }
            "--givens" => {
                i += 1;
                givens = match args.get(i).and_then(|s| s.parse().ok()) {
                    Some(v) => v,
                    None => {
                        eprintln!("--givens needs a number");
                        return 2;
                    }
                };
            }
            "--seed" => {
                i += 1;
                seed_opt = match args.get(i).and_then(|s| s.parse().ok()) {
                    Some(v) => Some(v),
                    None => {
                        eprintln!("--seed needs a number");
                        return 2;
                    }
                };
            }
            "--count" => {
                i += 1;
                count = match args.get(i).and_then(|s| s.parse().ok()) {
                    Some(v) => v,
                    None => {
                        eprintln!("--count needs a number");
                        return 2;
                    }
                };
            }
            "--out" => {
                i += 1;
                out = match args.get(i) {
                    Some(v) => Some(v.clone()),
                    None => {
                        eprintln!("--out needs a path");
                        return 2;
                    }
                };
            }
            "--query" => {
                i += 1;
                query = match args.get(i).map(|s| parse_query(s)) {
                    Some(Ok(q)) => Some(q),
                    _ => {
                        eprintln!("--query needs r,c (e.g. 0,1)");
                        return 2;
                    }
                };
            }
            "--max-passes" => {
                i += 1;
                max_passes = match args.get(i).and_then(|s| s.parse().ok()) {
                    Some(v) => v,
                    None => {
                        eprintln!("--max-passes needs a number");
                        return 2;
                    }
                };
            }
            "--no-solution" => with_solution = false,
            "--gui" => {}
            "--help" | "-h" => {
                print_usage();
                return 0;
            }
            other => {
                eprintln!("unknown arg: {}", other);
                print_usage();
                return 2;
            }
        }
        i += 1;
    }

    if !(2..=9).contains(&size) {
        eprintln!("size must be 2..=9, got {}", size);
        return 2;
    }
    if count == 0 {
        eprintln!("count must be >= 1");
        return 2;
    }
    if max_passes == 0 {
        eprintln!("max-passes must be >= 1");
        return 2;
    }

    let base_seed = seed_opt.unwrap_or_else(random_seed);
    let mut failures = 0usize;

    // --out with count>1 is a directory; otherwise a file.
    let out_dir = out.clone().filter(|_| count > 1);
    if let Some(dir) = &out_dir {
        if let Err(e) = std::fs::create_dir_all(dir) {
            eprintln!("cannot create directory {}: {}", dir, e);
            return 1;
        }
    }

    for k in 0..count {
        let s = base_seed.wrapping_add(k as u64);
        let opts = GenOptions {
            size,
            givens,
            seed: s,
            max_passes,
            query,
        };
        match generate(&opts) {
            Ok(g) => {
                let text = render_file_text(&g, with_solution);
                match (&out, count) {
                    (None, 1) => print!("{}", text),
                    (None, _) => {
                        println!("# --- puzzle {} (seed {}) ---", k + 1, s);
                        print!("{}", text);
                    }
                    (Some(path), 1) => {
                        if let Some(parent) = std::path::Path::new(path).parent() {
                            if !parent.as_os_str().is_empty() {
                                if let Err(e) = std::fs::create_dir_all(parent) {
                                    eprintln!("cannot create {}: {}", parent.display(), e);
                                    failures += 1;
                                    continue;
                                }
                            }
                        }
                        match std::fs::write(path, &text) {
                            Ok(()) => println!("wrote {} ({})", path, g.summary()),
                            Err(e) => {
                                eprintln!("cannot write {}: {}", path, e);
                                failures += 1;
                            }
                        }
                    }
                    (Some(dir), _) => {
                        let name = format!("ettu_s{}g{}_{}.txt", size, g.givens, s);
                        let full = std::path::Path::new(dir).join(name);
                        match std::fs::write(&full, &text) {
                            Ok(()) => println!("wrote {} ({})", full.display(), g.summary()),
                            Err(e) => {
                                eprintln!("cannot write {}: {}", full.display(), e);
                                failures += 1;
                            }
                        }
                    }
                }
            }
            Err(e) => {
                eprintln!("puzzle {} (seed {}): FAILED: {}", k + 1, s, e);
                failures += 1;
            }
        }
    }
    if failures > 0 {
        1
    } else {
        0
    }
}

